    "Умный Уход подбирает уходовую косметику по типу кожи, задачам и бюджету.\n"
    "Подбор строится по этапам: очищение, активы, крем, SPF.\n\n"

    "*Это консультация дерматолога?*\n"
    "Нет. Бот не заменяет врача, а помогает сориентироваться в уходе.\n\n"

    "*Какие бренды используются?*\n"
    "Bioderma, La Roche-Posay, CeraVe, COSRX, Avène, SVR, Uriage, "
    "The Ordinary, Paula’s Choice, Medik8 и другие.\n\n"

    "*Как подбираются средства?*\n"
    "Учитываются тип кожи, проблемы, бюджет и этап ухода.\n\n"

    "*Почему иногда вариантов мало?*\n"
    "Под конкретные параметры действительно может быть немного средств.\n"
    "В таких случаях предлагаются ближайшие безопасные варианты.\n\n"

    "*Что такое PRO-режим?*\n"
    "PRO даёт больше вариантов на каждом этапе, доступ к расширенным активам "
    "и более точный подбор.\n\n"

    "*Подходит ли PRO новичкам?*\n"
    "Да. PRO не означает агрессивный уход — только больше гибкости.\n\n"

