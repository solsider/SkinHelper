def register(bot, user_data: dict):

    @bot.message_handler(func=lambda m: m.text == "ℹ️ FAQ")
    def show_faq(message):
        bot.send_message(
            message.chat.id,
            FAQ_TEXT,
            parse_mode="Markdown",
            reply_markup=main_menu_keyboard()
        )
